def _num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0


def fclass_code(p):
    return (p.get("fclass") or "").split(" ")[0]


def is_mass(p):
    """Объект с массовым пребыванием людей (п. 5 ППР)."""
    return _num(p.get("max_people")) >= 50 or bool(p.get("workplaces10"))


def has(s, code):
    return code in s


def any_spz(s):
    return any(SYSTEMS[c]["spz"] for c in s if c in SYSTEMS)


def over_service_life(s, year_now):
    out = []
    for code, params in s.items():
        if code not in SYSTEMS or not SYSTEMS[code]["spz"]:
            continue
        y, life = _num(params.get("year")), _num(params.get("life")) or 10
        if y and y + life <= year_now:
            out.append(SYSTEMS[code]["name"])
    return out


