def warnings(p, s, year_now):
    """Подсказки по анкете: чего, вероятно, не хватает на объекте."""
    out = []
    fc = fclass_code(p)
    if fc in FCLASSES_SIGNAL_DUPLICATION and not has(s, "monitoring"):
        out.append(f"Класс {fc}: требуется дублирование сигнала о пожаре на пульт пожарной охраны "
                   "(ч. 7 ст. 83 123-ФЗ), а в анкете нет системы вывода сигнала.")
    if not has(s, "extinguishers"):
        out.append("В анкете не указаны огнетушители — объект должен быть оснащён первичными средствами "
                   "пожаротушения (ППР п. 60, разд. XIX).")
    if is_mass(p) and not has(s, "soue"):
        out.append("Объект с массовым пребыванием людей, но СОУЭ не указана — проверьте по СП 3.13130.")
    if is_mass(p) and not has(s, "aps") and not has(s, "aupt"):
        out.append("Нет АПС/АУПТ при массовом пребывании людей — проверьте требования СП 486.1311500.")
    old = over_service_life(s, year_now)
    if old:
        out.append("Срок службы истёк: " + "; ".join(old) + ". Нужны ежегодные испытания или замена (ППР п. 54).")
    fp = s.get("fireproof")
    if fp and _num(fp.get("year")) and _num(fp.get("life")) and _num(fp["year"]) + _num(fp["life"]) <= year_now:
        out.append("Истёк срок службы огнезащитного покрытия — требуется повторная обработка или испытания (ППР п. 13).")
    return out
